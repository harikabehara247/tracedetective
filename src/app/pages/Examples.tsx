import { formatMs } from '../../core';
import { SAMPLES } from '../../fixtures';
import { sampleTraceId, useTraces } from '../store';
import { ButtonLink, Card, PageHeader, SeverityBadge, SyntheticBadge, useDocumentTitle } from '../ui';

const SCENARIO_LABEL = { healthy: 'Baseline', database: 'Database bottleneck', external: 'External dependency', error: 'Failure' } as const;

export function Examples() {
  useDocumentTitle('Examples');
  const { get } = useTraces();
  return (
    <div>
      <PageHeader title="Example traces">
        Four synthetic scenarios of the same <code>POST /api/orders</code> endpoint. They were generated by a script in the repository to show common
        patterns. They are not measurements of a real system.
      </PageHeader>
      <div className="grid gap-4 md:grid-cols-2">
        {SAMPLES.map((s) => {
          const a = get(sampleTraceId(s.id))!.analysis;
          const top = a.findings[0];
          return (
            <Card key={s.id} as="article" className="flex flex-col">
              <div className="flex flex-wrap items-center gap-2">
                <span className="text-xs font-semibold uppercase tracking-wide text-violet">{SCENARIO_LABEL[s.scenario]}</span>
                <SyntheticBadge synthetic />
              </div>
              <h2 className="mt-2 text-lg font-semibold">{s.title}</h2>
              <p className="mt-1 flex-1 text-sm text-muted">{s.summary}</p>
              <dl className="mt-3 flex flex-wrap gap-x-6 gap-y-1 text-sm">
                <div><dt className="inline text-muted">Duration </dt><dd className="inline tabular-nums">{formatMs(a.durationMs)}</dd></div>
                <div><dt className="inline text-muted">Spans </dt><dd className="inline">{a.ordered.length}</dd></div>
                <div><dt className="inline text-muted">Errors </dt><dd className="inline">{a.errorCount}</dd></div>
              </dl>
              {top && (
                <p className="mt-3 flex items-start gap-2 text-sm">
                  <SeverityBadge severity={top.severity} /> <span>{top.title}</span>
                </p>
              )}
              <div className="mt-4 flex flex-wrap gap-2">
                <ButtonLink to={`/trace/${sampleTraceId(s.id)}`} variant="primary">Open trace</ButtonLink>
                {s.id !== 'healthy-order' && (
                  <ButtonLink to={`/compare?baseline=${sampleTraceId('healthy-order')}&current=${sampleTraceId(s.id)}`}>Compare with healthy</ButtonLink>
                )}
              </div>
            </Card>
          );
        })}
      </div>
    </div>
  );
}
